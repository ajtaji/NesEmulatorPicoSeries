"""Generate desktop/cpu_vectors.pbi: every documented 6502 opcode from random machine states, with py65 as
the independent oracle (as rp2040/Diagnostics/zp_vectors.pico is for the boards).

Each vector: the instruction at $0400 (opcode + 2 operand bytes), A X Y P S before, 16 bytes of memory at a
pointer page ($00F0-$00FF, for zero page and indirect pointers) and 16 at a data page ($0600-$060F, where
absolute and indirect operands point), then A X Y P S PC after, the cycles taken, and the 16 data-page and
16 zero-page bytes after. Decimal mode stays clear (the 2A03 has none). BRK is left out: it reads the
cartridge's IRQ vector, which the desktop test does not control.

  py -3 tools/gen_desktop_cpu_vectors.py
"""
import random
from pathlib import Path
from py65.devices.mpu6502 import MPU

ROOT = Path(__file__).resolve().parents[1]
PER_OPCODE = 8
random.seed(6502)

mpu0 = MPU()
documented = [op for op in range(256) if mpu0.disassemble[op][0] != '???' and op != 0x00]


def operand_for(mode):
    """Operand bytes that keep every access inside RAM the test sets up."""
    if mode in ('zpg', 'zpx', 'zpy'):
        return random.choice([0xF0, 0xF4, 0xF8, 0xFC, 0xFF, 0x10]), 0
    if mode in ('inx', 'iny'):
        return random.choice([0xF0, 0xF2, 0xF6, 0xFA, 0xFE]), 0
    if mode in ('abs', 'abx', 'aby'):
        a = random.choice([0x0600, 0x0604, 0x05F8, 0x05FF, 0x060E])
        return a & 255, a >> 8
    if mode == 'ind':
        a = random.choice([0x00F0, 0x00F4, 0x00FF])     # $00FF: the page-wrap bug
        return a & 255, a >> 8
    if mode == 'rel':
        return random.choice([0x02, 0x10, 0x7F, 0x80, 0xF0, 0xFE]), 0
    return random.randint(0, 255), random.randint(0, 255)


def effective(mode, lo, hi, x, y, zp):
    """The address an indexed or indirect operand reaches (None for the other modes)."""
    def zpb(a):
        a &= 255
        return zp[a - 0xF0] if a >= 0xF0 else 0
    if mode == 'inx':
        return zpb(lo + x) | (zpb(lo + x + 1) << 8)
    if mode == 'iny':
        return ((zpb(lo) | (zpb(lo + 1) << 8)) + y) & 0xFFFF
    if mode in ('abx', 'aby'):
        return ((lo | (hi << 8)) + (x if mode == 'abx' else y)) & 0xFFFF
    return None


def one_vector(op, mode):
    """One random state; None when its operand would leave the 2 KiB of RAM (the NES mirrors it at
    $0800-$1FFF and has registers above, py65 has flat memory, so such a case tests nothing)."""
    if True:
        mpu = MPU()
        mem = mpu.memory
        zp = [random.randint(0, 255) for _ in range(16)]
        data = [random.randint(0, 255) for _ in range(16)]
        # indirect pointers aim at the data page, its edge, or page 5's last bytes (page crossing)
        for p in range(0, 16, 2):
            if random.random() < 0.7:
                t = random.choice([0x0600, 0x0602, 0x05F8, 0x05FE, 0x060A])
                zp[p], zp[(p + 1) % 16] = t & 255, t >> 8
        for i in range(16):
            mem[0xF0 + i] = zp[i]
            mem[0x600 + i] = data[i]
        # page 5's last 16 bytes mirror the data page, so a page-crossing access reads known values
        for i in range(16):
            mem[0x5F0 + i] = data[i] ^ 0x5A
        lo, hi = operand_for(mode)
        mem[0x400], mem[0x401], mem[0x402] = op, lo, hi
        a, x, y = random.randint(0, 255), random.randint(0, 255), random.randint(0, 255)
        if mode in ('abx', 'aby', 'zpx', 'zpy', 'inx', 'iny') and random.random() < 0.5:
            x, y = random.choice([0, 1, 4, 15, 16, 255]), random.choice([0, 1, 4, 15, 16, 255])
        ea = effective(mode, lo, hi, x, y, zp)
        if ea is not None and ea >= 0x0800:
            return None
        p = (random.randint(0, 255) | 0x20) & ~0x08 & ~0x10
        s = random.choice([0xFD, 0xF0, 0x80, 0x02, 0x00, 0xFF])
        for i in range(8):     # stack bytes RTS/RTI/PLA/PLP read
            mem[0x100 + ((s + 1 + i) & 255)] = random.randint(0, 255)
        mpu.pc, mpu.a, mpu.x, mpu.y, mpu.p, mpu.sp = 0x400, a, x, y, p, s
        stack_before = [mem[0x100 + ((s + 1 + i) & 255)] for i in range(8)]
        cycles0 = mpu.processorCycles
        mpu.step()
        cycles = mpu.processorCycles - cycles0
        after_data = [mem[0x600 + i] for i in range(16)]
        after_zp = [mem[0xF0 + i] for i in range(16)]
        after_stack = [mem[0x100 + ((s - 2 + i) & 255)] for i in range(4)]
        return ([op, lo, hi, a, x, y, p, s] + zp + data + stack_before +
                [mpu.a, mpu.x, mpu.y, mpu.p | 0x20 | 0x10, mpu.sp, mpu.pc & 255, mpu.pc >> 8, cycles] +
                after_data + after_zp + after_stack)


rows = []
for op in documented:
    name, mode = mpu0.disassemble[op]
    k = 0
    while k < PER_OPCODE:
        r = one_vector(op, mode)
        if r is not None:
            rows.append(r)
            k += 1

width = len(rows[0])
out = [f'; Generated by tools/gen_desktop_cpu_vectors.py with py65 as the oracle: {len(rows)} vectors,',
       f'; {PER_OPCODE} per documented opcode (BRK excepted). Layout: see the generator. {width} bytes each.',
       f'#CPU_VECTOR_COUNT={len(rows)}', f'#CPU_VECTOR_BYTES={width}', 'DataSection', 'CpuVectors:']
for r in rows:
    out.append('  Data.a ' + ','.join(str(v) for v in r))
out.append('EndDataSection')
(ROOT / 'desktop' / 'cpu_vectors.pbi').write_text('\n'.join(out) + '\n', newline='\n')
print(f'{len(rows)} vectors for {len(documented)} opcodes, {width} bytes each')
