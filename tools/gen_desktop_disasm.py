"""Generate desktop/disasm.pbi: the 6502's documented opcodes (from py65's own table) as a PureBasic
disassembler for the desktop window's CPU pane.

  py -3 tools/gen_desktop_disasm.py
"""
from pathlib import Path
from py65.devices.mpu6502 import MPU
from py65.disassembler import Disassembler
mpu = MPU()
dis = Disassembler(mpu)
modes = {'imp': 0, 'acc': 1, 'imm': 2, 'zpg': 3, 'zpx': 4, 'zpy': 5, 'abs': 6, 'abx': 7, 'aby': 8,
         'ind': 9, 'inx': 10, 'iny': 11, 'rel': 12}
names, mode = [], []
for op in range(256):
    n, m = mpu.disassemble[op]
    if n == '???':
        names.append('???'); mode.append(0)
    else:
        names.append(n); mode.append(modes[m])
out = ['; Generated by tools/gen_desktop_disasm.py from py65\'s 6502 table. Documented opcodes; others "???".',
       'EnableExplicit',
       'Global Dim DisName$(256)', 'Global Dim DisMode.i(256)',
       '; mode: 0 implied, 1 A, 2 #imm, 3 zp, 4 zp,X, 5 zp,Y, 6 abs, 7 abs,X, 8 abs,Y, 9 (ind), 10 (zp,X), 11 (zp),Y, 12 rel',
       'Procedure DisInit()', '  Protected i.i, s$']
out.append('  Restore DisNames')
out.append('  For i=0 To 255 : Read.s s$ : DisName$(i)=s$ : Next')
out.append('  Restore DisModes')
out.append('  For i=0 To 255 : Read.a DisMode(i) : Next')
out.append('EndProcedure')
out.append('''Procedure.i DisLength(op.i)
  Select DisMode(op)
    Case 0, 1 : ProcedureReturn 1
    Case 6, 7, 8, 9 : ProcedureReturn 3
    Default : ProcedureReturn 2
  EndSelect
EndProcedure
; One instruction at addr, read through peek (a callback that does not disturb the machine):
; "C000  A9 10     LDA #$10".
Prototype.i DisPeek(addr.i)
Procedure.s DisLine(addr.i, peek.DisPeek)
  Protected op.i, n.i, b1.i, b2.i, t$, bytes$, w.i
  op=peek(addr) : n=DisLength(op) : b1=peek((addr+1)&$FFFF) : b2=peek((addr+2)&$FFFF) : w=b1|(b2<<8)
  bytes$=RSet(Hex(op),2,"0")
  If n>1 : bytes$+" "+RSet(Hex(b1),2,"0") : EndIf
  If n>2 : bytes$+" "+RSet(Hex(b2),2,"0") : EndIf
  If DisName$(op)="???" : ProcedureReturn RSet(Hex(addr),4,"0")+"  "+LSet(bytes$,9)+" .db $"+RSet(Hex(op),2,"0") : EndIf
  Select DisMode(op)
    Case 0 : t$=""
    Case 1 : t$=" A"
    Case 2 : t$=" #$"+RSet(Hex(b1),2,"0")
    Case 3 : t$=" $"+RSet(Hex(b1),2,"0")
    Case 4 : t$=" $"+RSet(Hex(b1),2,"0")+",X"
    Case 5 : t$=" $"+RSet(Hex(b1),2,"0")+",Y"
    Case 6 : t$=" $"+RSet(Hex(w),4,"0")
    Case 7 : t$=" $"+RSet(Hex(w),4,"0")+",X"
    Case 8 : t$=" $"+RSet(Hex(w),4,"0")+",Y"
    Case 9 : t$=" ($"+RSet(Hex(w),4,"0")+")"
    Case 10 : t$=" ($"+RSet(Hex(b1),2,"0")+",X)"
    Case 11 : t$=" ($"+RSet(Hex(b1),2,"0")+"),Y"
    Case 12 : t$=" $"+RSet(Hex((addr+2+((b1!128)-128))&$FFFF),4,"0")
  EndSelect
  ProcedureReturn RSet(Hex(addr),4,"0")+"  "+LSet(bytes$,9)+" "+DisName$(op)+t$
EndProcedure''')
out.append('DataSection')
out.append('DisNames:')
for i in range(0, 256, 16):
    out.append('  Data.s ' + ','.join(f'"{n}"' for n in names[i:i + 16]))
out.append('DisModes:')
for i in range(0, 256, 32):
    out.append('  Data.a ' + ','.join(str(m) for m in mode[i:i + 32]))
out.append('EndDataSection')
(Path(__file__).resolve().parents[1] / 'desktop' / 'disasm.pbi').write_text('\n'.join(out) + '\n', newline='\n')
print('ok', sum(n != '???' for n in names), 'documented opcodes')
