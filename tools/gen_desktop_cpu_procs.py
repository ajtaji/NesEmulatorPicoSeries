"""Generate desktop/core/cpu2a03_procs.pbi: the same 2A03 as desktop/core/cpu2a03.pbi, dispatched through a
table of procedure pointers instead of labels-as-values (computed goto in the C backend). It exists for one
measurement, desktop/dispatch_bench.pb: which dispatch is faster on the PC. Each `OpXX:` block of the
generated CPU becomes `Procedure CpuProcXX()`; `CpuNextOp(c)` becomes "charge, count, return" and the loop in
CpuRunProc fetches and calls while the budget lasts. Same contract as CpuRun (cycles run, Stopped on an
illegal opcode).

  py -3 tools/gen_desktop_cpu_procs.py      (after tools/port_desktop.py)
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
src = (ROOT / 'desktop' / 'core' / 'cpu2a03.pbi').read_text(encoding='utf-8').split('\n')

start = next(i for i, l in enumerate(src) if re.match(r'^Op[0-9A-F]{2}:', l))
end = next(i for i, l in enumerate(src) if l.startswith('Done:'))

ops = []          # (hex, body lines)
cur = None
for line in src[start:end]:
    m = re.match(r'^Op([0-9A-F]{2}):(.*)$', line)
    if m:
        cur = (m.group(1), m.group(2).strip(), [])
        ops.append(cur)
        continue
    body = re.sub(r'CpuNextOp\((\d+)\)', r'CpuProcNext(\1)', line)
    if 'Goto' in body or '!goto' in body:
        raise SystemExit(f'unexpected jump in Op{cur[0]}: {line.strip()}')
    cur[2].append(body)

out = ['; Generated by tools/gen_desktop_cpu_procs.py from desktop/core/cpu2a03.pbi - do not edit; regenerate.',
       '; The 2A03 through a procedure-pointer table (the measurement in desktop/dispatch_bench.pb).',
       'EnableExplicit',
       'Prototype CpuProcOp()',
       'Global Dim CpuProcTable.i(256)',
       'Global CpuProcReady.i',
       '',
       'Macro CpuProcNext(c)',
       '  CpuTick(c)',
       '  NesInstructions = NesInstructions + 1',
       '  ProcedureReturn',
       'EndMacro',
       '',
       'Procedure CpuProcIllegal()',
       '  PC = (PC - 1) & $FFFF',
       '  BadOpcode = NesRead(PC)',
       '  Stopped = 1',
       'EndProcedure',
       '']
for hx, comment, body in ops:
    out.append(f'Procedure CpuProc{hx}() ; {comment}')
    out.extend(body)
    out.append('EndProcedure')
out += ['',
        'Procedure.i CpuRunProc(n.i)',
        '  Protected op.CpuProcOp, i.i',
        '  If n <= 0 Or Stopped : ProcedureReturn 0 : EndIf',
        '  If CpuProcReady = 0',
        '    For i = 0 To 255 : CpuProcTable(i) = @CpuProcIllegal() : Next']
out += [f'    CpuProcTable(${hx}) = @CpuProc{hx}()' for hx, _, _ in ops]
out += ['    CpuProcReady = 1',
        '  EndIf',
        '  If NesStall',
        '    CpuCycles = CpuCycles + NesStall',
        '    NesStall = 0',
        '  EndIf',
        '  NesRunStart = CpuCycles',
        '  CpuInWindow = 1',
        '  Budget = n',
        '  Left = n',
        '  Repeat',
        '    Tmp = NesRead(PC)',
        '    PC = (PC + 1) & $FFFF',
        '    op = CpuProcTable(Tmp)',
        '    op()',
        '  Until Left <= 0 Or Stopped',
        '  CpuCycles = NesRunStart + Budget - Left',
        '  CpuInWindow = 0',
        '  ProcedureReturn CpuCycles - NesRunStart',
        'EndProcedure',
        '']
(ROOT / 'desktop' / 'core' / 'cpu2a03_procs.pbi').write_text('\n'.join(out), encoding='utf-8', newline='\n')
print(f'{len(ops)} opcode procedures')
