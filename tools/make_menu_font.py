"""Render the boot menu's text and the FPS readout's digits ONCE, on the PC, with a TrueType engine (FreeType,
through Pillow), into rp2040/menu_font.pico. The firmware never rasterises a font: it blits these glyphs.

    py -3 tools/make_menu_font.py            # write rp2040/menu_font.pico (then tools/port_rp2350.py)
    py -3 tools/make_menu_font.py --check    # exit 1 if the committed file is not what this tool writes

Fonts (SIL Open Font License 1.1, licences beside them in fonts/source/):
  - Menu text: rendered from Lato Regular. Lato has the Reserved Font Name "Lato", so these bitmaps are not
    called Lato: they are "Menu Sans", based on Lato.
  - FPS digits: rendered from JetBrains Mono Regular ("Menu Mono"), so the figures keep one width.

What it writes:
  - MenuSans<size>: printable ASCII (32-126) at two sizes, 4-bit coverage (anti-aliased), packed two pixels a
    byte, rows padded to a byte. Per glyph 5 metric bytes: width, height, left offset (+64), top offset from
    the line top, advance. Plus a 16-bit offset into the bitmap block. The firmware blends the coverage between
    the text colour and the known background.
  - HudSprites: the readout's 18 glyphs (0-9, F P S E M U, space, dot) as ready 8x10 RGB565 sprites, white on
    black, in the cell the display drivers already place (see the outputs' VideoHudRect).
"""
import argparse, sys
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
SANS = ROOT / 'fonts/source/lato/Lato-Regular.ttf'
MONO = ROOT / 'fonts/source/jetbrainsmono/JetBrainsMono-Regular.ttf'
OUT = ROOT / 'rp2040/menu_font.pico'
SIZES = {'Large': 20, 'Small': 14}          # heading; list, prompts
HUD_GLYPHS = '0123456789FPSEMU .'          # HudGlyph's indices 0..17
HUD_SIZE = 11                              # JetBrains Mono pixel size for the 8x10 cell


def sans_font(size):
    return ImageFont.truetype(str(SANS), size, layout_engine=ImageFont.Layout.BASIC)


def render_sans(size):
    """[(width, height, left, top, advance, rows)] for ASCII 32..126; rows = list of 4-bit values."""
    font = sans_font(size)
    ascent, descent = font.getmetrics()
    glyphs = []
    for code in range(32, 127):
        ch = chr(code)
        advance = int(round(font.getlength(ch)))
        box = font.getbbox(ch)              # relative to the drawing origin at the line top
        if box[2] <= box[0] or box[3] <= box[1]:
            glyphs.append((0, 0, 0, 0, advance, []))
            continue
        w, h = box[2] - box[0], box[3] - box[1]
        img = Image.new('L', (w, h), 0)
        ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255)
        px = img.tobytes()
        rows = [[(px[y * w + x] * 15 + 127) // 255 for x in range(w)] for y in range(h)]
        glyphs.append((w, h, box[0], box[1], advance, rows))
    return ascent + descent, glyphs


def rgb565(level):
    r = (level * 31 + 127) // 255
    g = (level * 63 + 127) // 255
    return (r << 11) | (g << 5) | r


def render_hud():
    font = ImageFont.truetype(str(MONO), HUD_SIZE, layout_engine=ImageFont.Layout.BASIC)
    # one baseline for every glyph: the digits' cap height centred in the 10-pixel cell
    top = font.getbbox('0')[1]
    height = font.getbbox('0')[3] - top
    oy = (10 - height) // 2 - top
    sprites = []
    for ch in HUD_GLYPHS:
        img = Image.new('L', (8, 10), 0)
        if ch != ' ':
            adv = font.getlength(ch)
            ox = int(round((8 - adv) / 2))
            ImageDraw.Draw(img).text((ox, oy), ch, font=font, fill=255)
        sprites.append([rgb565(v) for v in img.tobytes()])
    return sprites


def data_lines(kind, values, per_line):
    for i in range(0, len(values), per_line):
        yield '  Data.%s %s' % (kind, ','.join(str(v) for v in values[i:i + per_line]))


def generate():
    out = ['; GENERATED by tools/make_menu_font.py - do not edit; run it, then tools/port_rp2350.py.',
           '; Menu Sans: glyphs rendered from Lato Regular (SIL OFL 1.1, Reserved Font Name "Lato"; these bitmaps',
           '; are not called Lato). Menu Mono: the FPS digits, rendered from JetBrains Mono Regular (SIL OFL 1.1).',
           '; Licences and copyright notices: fonts/source/*/OFL.txt.',
           'DataSection']
    for name, size in SIZES.items():
        line, glyphs = render_sans(size)
        metrics, offsets, bits = [], [], []
        for w, h, left, top, advance, rows in glyphs:
            metrics += [w, h, left + 64, top, advance]
            offsets.append(len(bits))
            for row in rows:
                row = row + [0] * (len(row) & 1)
                bits += [row[i] | (row[i + 1] << 4) for i in range(0, len(row), 2)]
        assert len(bits) < 65536
        out.append('MenuSans%sLine: Data.a %d' % (name, line))
        out.append('MenuSans%sMetrics:' % name)
        out += data_lines('a', metrics, 40)
        out.append('MenuSans%sOffsets:' % name)
        out += data_lines('u', offsets, 24)
        out.append('MenuSans%sBits:' % name)
        out += data_lines('a', bits, 40)
    out.append('HudSprites:')
    for sprite in render_hud():
        out += data_lines('u', sprite, 40)
    out.append('EndDataSection')
    return '\n'.join(out) + '\n'


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument('--check', action='store_true', help='compare with the committed file instead of writing it')
    a = p.parse_args()
    text = generate()
    if a.check:
        have = OUT.read_text(encoding='ascii').replace('\r\n', '\n') if OUT.exists() else ''
        if have != text:
            sys.exit('menu_font.pico is not what tools/make_menu_font.py writes: run it')
        print('menu_font.pico current')
        return
    OUT.write_text(text, encoding='ascii', newline='\n')
    print('wrote', OUT.relative_to(ROOT), len(text), 'characters')


if __name__ == '__main__':
    main()
